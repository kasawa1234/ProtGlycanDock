import os
import shutil
import glob
from os.path import join as opjoin
from typing import Any, Dict, List, Mapping, Sequence, Tuple, Union
from protenix.web_service.biogeom_colabfold import run_mmseqs2 as run_mmseqs2_biogeom
VANILLA_MMSEQS_SERVICE_HOST_URL = "http://172.18.1.52:60123"


def read_a3m(a3m_file: str) -> Tuple[List[str], List[str]]:
    heads = []
    seqs = []
    with open(a3m_file, "r") as infile:
        for line in infile:
            if line.startswith(">"):
                heads.append(line)
            else:
                seqs.append(line)
    return heads, seqs


# vanilla mmseqs2 server
def biogeom_msa_search(
    query_tags_unique: Sequence[str],
    query_seqs_unique: Sequence[str],
    msa_res_dir: str,
    host_url: str = VANILLA_MMSEQS_SERVICE_HOST_URL,
    remove_tmp_files: bool = True,
) -> Sequence[str]:
    """
    Args
        query_tags_unique: a list of unique tags for each query sequence
        query_seqs_unique: a list of unique query sequences
        msa_res_dir: the directory to save the msa results
        host_url: the host url of the vanilla mmseqs2 server
        remove_tmp_files: whether to remove the temporary files generated by mmseqs2
    Returns
        msa_res_subdirs: a list of subdirectories containing the msa results,
            following the order of query_tags_unique
    """
    # switch to biogeometry's convention
    alignment_dir = msa_res_dir
    os.makedirs(alignment_dir, exist_ok=True)
    mmseqs_output_dir = opjoin(msa_res_dir, "tmp_mmseqs")
    use_env = True
    user_agent = "colabfold/1.0.0"
    for query_tag in query_tags_unique:
        assert not query_tag.startswith("tmp_mmseqs"), f"query_tag cannot start with tmp_mmseqs: {query_tag}"

    # search non-pairing msas without templates
    a3m_lines_mmseqs2 = run_mmseqs2_biogeom(
        query_seqs_unique,
        mmseqs_output_dir,
        use_env,
        use_templates=False,
        use_pairing=False,
        host_url=host_url,
        user_agent=user_agent,
    )

    # search pairing msas 
    if len(query_seqs_unique) > 1: # if not a homooligomers
        paired_a3m_lines = run_mmseqs2_biogeom(
            query_seqs_unique,
            mmseqs_output_dir,
            use_env,
            use_templates=False,
            use_pairing=True,
            pairing_strategy="greedy",
            host_url=host_url,
            user_agent=user_agent,
        )
    else: # homooligomers
        paired_a3m_lines = [f">101\n{query_seqs_unique[0]}\n"]

    # generate alignment directory
    msa_res_subdirs = []
    for index, (query_tag, query_seq) in enumerate(zip(query_tags_unique, query_seqs_unique)):
        msa_res_subdir = opjoin(alignment_dir, query_tag)
        os.makedirs(msa_res_subdir, exist_ok=True)
        with open(opjoin(msa_res_subdir, "non_pairing.a3m"), 'w') as fout:
            fout.write(a3m_lines_mmseqs2[index])
        # with open(opjoin(msa_res_subdir, "pairing.a3m"), 'w') as fout:
        #     fout.write(paired_a3m_lines[index])
        raw_pairing_a3m_lines = paired_a3m_lines[index].split("\n")
        heads, seqs, new_heads = [], [], []
        for line in raw_pairing_a3m_lines:
            if line.startswith(">"):
                heads.append(line)
            else:
                seqs.append(line)
        for i, (head, seq) in enumerate(zip(heads, seqs)):
            if i == 0: # the first sequence is the query sequence
                new_heads.append(head)
            else:
                new_head = f">UniRef100_adhoc_{i}/{head[1:]}"
                new_heads.append(new_head)
        with open(opjoin(msa_res_subdir, "pairing.a3m"), 'w') as fout:
            for new_head, seq in zip(new_heads, seqs):
                fout.write(f"{new_head}\n{seq}\n")
        msa_res_subdirs.append(msa_res_subdir)

    if remove_tmp_files: # remove all subdirectories starting with mmseqs_output_dir
        for dir in glob.glob(f"{mmseqs_output_dir}*"):
            shutil.rmtree(dir)
    
    return msa_res_subdirs


# modified mmseqs2 server, which return species id for uniref100 sequences
def biogeom_msa_search_post_pairing(
    query_tags_unique: Sequence[str],
    query_seqs_unique: Sequence[str],
    msa_res_dir: str,
    host_url: str = VANILLA_MMSEQS_SERVICE_HOST_URL,
    remove_tmp_files: bool = True,
) -> Sequence[str]:
    """
    Args
        query_tags_unique: a list of unique tags for each query sequence
        query_seqs_unique: a list of unique query sequences
        msa_res_dir: the directory to save the msa results
        host_url: the host url of the vanilla mmseqs2 server
        remove_tmp_files: whether to remove the temporary files generated by mmseqs2
    Returns
        msa_res_subdirs: a list of subdirectories containing the msa results,
            following the order of query_tags_unique
    """
    # switch to biogeometry's convention
    alignment_dir = msa_res_dir
    os.makedirs(alignment_dir, exist_ok=True)
    mmseqs_output_dir = opjoin(msa_res_dir, "tmp_mmseqs")
    use_env = True
    user_agent = "geoflow2/1.0.0"
    for query_tag in query_tags_unique:
        assert not query_tag.startswith("tmp_mmseqs"), f"query_tag cannot start with tmp_mmseqs: {query_tag}"

    # search non-pairing msas without templates
    a3m_lines_mmseqs2 = run_mmseqs2_biogeom(
        query_seqs_unique,
        mmseqs_output_dir,
        use_env,
        use_templates=False,
        use_pairing=False,
        host_url=host_url,
        user_agent=user_agent,
    )

    # generate alignment directory
    msa_res_subdirs = []
    for index, (query_tag, query_seq) in enumerate(zip(query_tags_unique, query_seqs_unique)):
        msa_res_subdir = opjoin(alignment_dir, query_tag)
        os.makedirs(msa_res_subdir, exist_ok=True)
        raw_a3m_path = opjoin(msa_res_subdir, "tmp.a3m")
        with open(raw_a3m_path, 'w') as fout:
            fout.write(a3m_lines_mmseqs2[index])

        heads, msa_seqs = read_a3m(raw_a3m_path)
        uniref100_lines = [">query\n", f"{query_seq}\n"]
        other_lines = [">query\n", f"{query_seq}\n"] 
        for head, msa_seq in zip(heads, msa_seqs):
            if msa_seq.rstrip("\n") == query_seq:
                continue
            if "UniRef" in head:
                uniref_id = head.split("\t")[0][1:]
                if len(uniref_id.split("_")) == 3: # uniref100 seq with species annot
                    head = head.replace(uniref_id, f"{uniref_id}/") # add / to the end of uniref100 id
                uniref100_lines.extend([head, msa_seq])
            else:
                other_lines.extend([head, msa_seq])
        with open(opjoin(msa_res_subdir, "pairing.a3m"), 'w') as fout:
            for line in uniref100_lines:
                fout.write(line)
        with open(opjoin(msa_res_subdir, "non_pairing.a3m"), 'w') as fout:
            for line in other_lines:
                fout.write(line)
        os.remove(raw_a3m_path)
        msa_res_subdirs.append(msa_res_subdir)

    if remove_tmp_files: # remove all subdirectories starting with mmseqs_output_dir
        for dir in glob.glob(f"{mmseqs_output_dir}*"):
            shutil.rmtree(dir)

    return msa_res_subdirs


